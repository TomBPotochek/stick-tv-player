package ph.opendtv.source;

import java.io.FileOutputStream;
import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

/**
 * Generates the Rust tables of crates/tuner from OpenDTV's Java data classes (It9175Data*, It9175Firmware*), so the
 * Rust port uses exactly the same firmware, register scripts and band tables. Lives in ph.opendtv.source because
 * It9175Profile is package-private. Run with tools/gen-tables/gen.sh (or gen.ps1).
 *
 * args: <output dir for .rs> <output dir for firmware .bin>
 */
public final class GenRustTables {
    public static void main(String[] args) throws IOException {
        Path rsDir = Paths.get(args[0]);
        Path binDir = Paths.get(args[1]);
        Files.createDirectories(rsDir);
        Files.createDirectories(binDir);
        gen(It9175Profile.PT275A, "PT275", "pt275", rsDir, binDir);
        gen(It9175Profile.PT275C, "PT275C", "pt275c", rsDir, binDir);
    }

    private static void gen(It9175Profile p, String ident, String file, Path rsDir, Path binDir) throws IOException {
        byte[] fw = p.firmware();
        int sum = 0;
        for (int c : p.fwChunks) sum += c;
        if (sum != fw.length) throw new IllegalStateException(ident + ": chunk sizes " + sum + " != firmware " + fw.length);
        try (FileOutputStream o = new FileOutputStream(binDir.resolve("fw_" + file + ".bin").toFile())) {
            o.write(fw);
        }
        try (PrintWriter w = new PrintWriter(rsDir.resolve("data_" + file + ".rs").toFile(), StandardCharsets.UTF_8)) {
            w.println("// GENERATED by tools/gen-tables from OpenDTV's It9175Profile." + (ident.equals("PT275") ? "PT275A" : ident)
                    + ". Do not edit by hand.");
            w.println("use super::profile::{Op, Op::*, Profile};");
            w.println();
            w.println("pub static " + ident + ": Profile = Profile {");
            w.println("    name: \"" + p.name + "\",");
            w.println("    firmware: include_bytes!(\"../../data/fw_" + file + ".bin\"),");
            w.print("    fw_chunks: &[");
            for (int i = 0; i < p.fwChunks.length; i++) w.print((i > 0 ? ", " : "") + p.fwChunks[i]);
            w.println("],");
            w.println("    init_a0: INIT_A0,");
            w.println("    init_b0: INIT_B0,");
            w.println("    tune_pre0: TUNE_PRE0,");
            w.println("    init_a1: INIT_A1,");
            w.println("    init_b1: INIT_B1,");
            w.println("    tune_pre1: TUNE_PRE1,");
            w.println("    bands0: BANDS0,");
            w.println("    bands1: BANDS1,");
            w.println("};");
            ops(w, "INIT_A0", p.initA0);
            ops(w, "INIT_B0", p.initB0);
            ops(w, "TUNE_PRE0", p.tunePre0);
            ops(w, "INIT_A1", p.initA1);
            ops(w, "INIT_B1", p.initB1);
            ops(w, "TUNE_PRE1", p.tunePre1);
            bands(w, "BANDS0", p.bands0);
            bands(w, "BANDS1", p.bands1);
        }
    }

    private static void ops(PrintWriter w, String name, String[] ops) {
        w.println();
        w.println("static " + name + ": &[Op] = &[");
        for (String op : ops) w.println("    " + op(op) + ",");
        w.println("];");
    }

    /** Same syntax It9175Tuner.exec parses. */
    private static String op(String op) {
        char c = op.charAt(0);
        int proc = op.charAt(1) - '0';
        String[] a = (op.length() > 3 ? op.substring(3) : "").split(":");
        switch (c) {
            case 'W': return "W(" + proc + ", 0x" + a[0] + ", &" + bytes(a[1]) + ")";
            case 'I': return "I(" + proc + ", 0x" + a[0] + ", &" + bytes(a[1]) + ")";
            case 'M': return "M(" + proc + ", 0x" + a[0] + ", 0x" + a[1] + ", 0x" + a[2] + ")";
            case 'V': return "V(" + proc + ")";
            case 'Q': return "Q(" + proc + ", 0x" + a[0] + ")";
            case 'P': return "P(" + proc + ", 0x" + a[0] + ")";
            default: throw new IllegalStateException("unknown op " + op);
        }
    }

    private static String bytes(String hex) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < hex.length(); i += 2) {
            if (i > 0) sb.append(", ");
            sb.append("0x").append(hex, i, i + 2);
        }
        return sb.append("]").toString();
    }

    private static void bands(PrintWriter w, String name, int[][] rows) {
        w.println();
        w.println("/// startKHz, fb25, fbb5, fbb6, fbb7, fbb9a, fbb9b, fbba");
        w.println("static " + name + ": &[[u32; 8]] = &[");
        for (int[] r : rows) {
            if (r.length != 8) throw new IllegalStateException(name + " row length " + r.length);
            StringBuilder sb = new StringBuilder("    [");
            for (int i = 0; i < 8; i++) sb.append(i > 0 ? ", " : "").append(r[i]);
            w.println(sb.append("],"));
        }
        w.println("];");
    }
}
